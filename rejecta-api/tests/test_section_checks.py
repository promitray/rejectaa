"""Section checklists decided by code: what they find, and what they must not claim."""

from __future__ import annotations

from pathlib import Path

import pytest

from services import paper_profile as pp
from services.section_checks import PaperText, check_sections

INTRO = (
    "Molecular generation has advanced quickly [1, 2]. Variational autoencoders are widely used [3-5]. "
    "Their latent spaces are poorly conditioned [6]. In this paper, we condition the latent space on a target "
    "property and show that optimisation improves."
)
METHODS = (
    "All networks were implemented using Keras [41] and TensorFlow [42]. We trained the model for 200 epochs with a "
    "learning rate of 0.001 and a batch size of 128. The optimizer was Adam. Training was performed on an NVIDIA "
    "RTX 2070 GPU. The dataset contains 250,000 molecules split into training and test sets."
)
RESULTS = (
    "The training and validation losses are shown in Fig. 2. Generated molecules are shown in Fig. 1. "
    "Validity was 98.77 ± 0.13 and uniqueness 98.31 ± 0.15 over 5 separate runs. Novelty was 99.75, "
    "the score was 104.29, the similarity 0.42 and success 98.25. Conditioning is not as advantageous for the "
    "constrained benchmark."
)
CONCLUSION = "We show that simple changes to VAEs improve molecular generation."
ABSTRACT = "We set a new state of the art at 104.29 and validity of 98.77."
CAPTIONS = (
    "Fig. 1: Molecules generated by randomly sampling the prior and decoding.\n\n"
    "Fig. 2: Training and validation losses and metrics collected over 200 epochs.\n\n"
)


def paper(
    sections: dict[str, str] | None = None,
    roles: dict[str, str] | None = None,
    full_text: str | None = None,
    abstract: str = ABSTRACT,
    article_type: str = pp.RESEARCH_ARTICLE,
) -> PaperText:
    sections = sections or {"introduction": INTRO, "methods": METHODS, "results": RESULTS, "discussion": CONCLUSION}
    roles = roles or {name: name for name in sections}
    text = full_text if full_text is not None else "\n\n".join([abstract, *sections.values(), CAPTIONS])
    return PaperText(text, abstract, sections, roles, article_type)


def item(found: dict, section: str, key: str):
    return next((c for c in found[section] if c.key == key), None)


# ------------------------------------------------------------------ introduction

def test_the_aim_is_found_and_quoted() -> None:
    found = check_sections(paper())
    aim = item(found, "introduction", "objective")
    assert aim.status == "met" and aim.quote.startswith("In this paper, we condition")


def test_a_phrase_about_earlier_work_is_not_taken_for_the_aim() -> None:
    intro = "VAEs are common [1]. The method proposed in this work by Smith was fast [2]. It was slow later."
    found = check_sections(paper({"introduction": intro, "results": RESULTS}))
    assert item(found, "introduction", "objective").status == "missing"


# ------------------------------------------------------------------ methods

def test_software_without_a_version_is_named() -> None:
    check = item(check_sections(paper()), "methods", "software_version")
    assert check.status == "issue" and "Keras, TensorFlow" in check.detail
    assert "Keras [41]" in check.quote


def test_software_with_a_version_is_met() -> None:
    methods = METHODS.replace("Keras [41] and TensorFlow [42]", "Keras 2.4.3 and TensorFlow 2.3.0")
    found = check_sections(paper({"introduction": INTRO, "methods": methods, "results": RESULTS}))
    assert item(found, "methods", "software_version").status == "met"


def test_a_trained_model_needs_a_seed_and_shows_its_hardware() -> None:
    found = check_sections(paper())
    assert item(found, "methods", "hardware").status == "met"
    assert item(found, "methods", "seed").status == "missing"


def test_seed_and_hardware_are_not_asked_of_a_paper_that_trains_nothing() -> None:
    methods = "The polymer was dissolved in THF and heated to 80 °C for 2 h. Yields were 85.2, 90.1 and 77.3%."
    found = check_sections(paper({"introduction": INTRO, "methods": methods, "results": RESULTS}))
    assert item(found, "methods", "seed") is None and item(found, "methods", "hardware") is None


def test_repeat_runs_are_found_in_the_results_too() -> None:
    check = item(check_sections(paper()), "methods", "replicates")
    assert check.status == "met" and "5 separate runs" in check.quote


def test_p_values_without_a_named_test_are_major() -> None:
    results = RESULTS + " The treated group differed (p < 0.05)."
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    check = item(found, "methods", "statistics")
    assert check.status == "missing" and check.severity == "major"


def test_a_probability_is_not_a_p_value() -> None:
    results = RESULTS + " Dropout was applied with p = 0.5."
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    assert item(found, "methods", "statistics") is None


def test_animals_without_an_ethics_statement_are_major() -> None:
    methods = METHODS + " Tumours were grown in nude mice and treated in vivo with the compound."
    check = item(check_sections(paper({"introduction": INTRO, "methods": methods, "results": RESULTS})), "methods", "ethics")
    assert check.status == "missing" and check.severity == "major"


def test_an_ethics_statement_after_the_references_counts() -> None:
    methods = METHODS + " Tumours were grown in nude mice and treated in vivo with the compound."
    sections = {"introduction": INTRO, "methods": methods, "results": RESULTS}
    text = "\n\n".join([ABSTRACT, *sections.values(), "References\n1. A. B, J. Chem. 2020.",
                        "All animal procedures were approved by the Institutional Animal Care and Use Committee (IACUC)."])
    assert item(check_sections(paper(sections, full_text=text)), "methods", "ethics").status == "met"


def test_data_availability() -> None:
    assert item(check_sections(paper()), "methods", "data_availability").status == "missing"
    sections = {"introduction": INTRO, "methods": METHODS + " The code is publicly available at github.com/x/y.", "results": RESULTS}
    assert item(check_sections(paper(sections)), "methods", "data_availability").status == "met"


def test_a_sentence_about_the_literature_is_not_a_data_statement() -> None:
    methods = METHODS + " Little information is available in the literature on this class."
    sections = {"introduction": INTRO, "methods": methods, "results": RESULTS}
    assert item(check_sections(paper(sections)), "methods", "data_availability").status == "missing"


# ------------------------------------------------------------------ results, figures and the abstract

def test_a_sentence_that_describes_another_figure_is_flagged() -> None:
    results = (
        "The training and validation losses per epoch are shown in Fig. 1. Generated molecules are shown in Fig. 2."
        + RESULTS[RESULTS.index(" Validity"):]
    )
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    check = item(found, "results", "figure_number")
    assert check is not None and "Fig. 2" in check.detail and check.quote.startswith("The training and validation losses")


def test_correct_figure_numbers_are_not_flagged() -> None:
    assert item(check_sections(paper()), "results", "figure_number") is None


def test_a_captioned_figure_the_text_never_cites_is_reported() -> None:
    results = RESULTS.replace(" Generated molecules are shown in Fig. 1.", "")
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    check = item(found, "results", "figure_unreferenced")
    assert check is not None and "Fig. 1" in check.label


def test_ranges_and_glued_citation_numbers_count_as_citations_of_each_figure() -> None:
    captions = "".join(f"Scheme {n}. Synthesis route number {n} of the series.\n\n" for n in range(1, 5))
    results = RESULTS + " The routes are compared in Schemes 1–3, as shown in\nScheme 4.41 Yields were similar."
    sections = {"introduction": INTRO, "methods": METHODS, "results": results}
    text = "\n\n".join([ABSTRACT, *sections.values(), CAPTIONS, captions])
    found = check_sections(paper(sections, full_text=text))
    assert not [c for c in found["results"] if c.key == "figure_unreferenced" and "Scheme" in c.label]


def test_a_number_in_the_abstract_that_the_paper_never_gives() -> None:
    found = check_sections(paper(abstract="We reach a score of 104.29 and a validity of 99.91."))
    flagged = [c for c in found["results"] if c.key == "abstract_number"]
    assert [c.label for c in flagged] == ["Abstract value 99.91 is not in the paper"]


def test_a_rounded_abstract_number_matches_the_exact_value() -> None:
    found = check_sections(paper(abstract="Validity reached 98.8 and the score 104.3."))
    assert not [c for c in found["results"] if c.key == "abstract_number"]


def test_values_without_any_spread_are_reported() -> None:
    results = "Yields were 85.2, 90.1, 77.3, 64.0, 91.9 and 70.4% for the six substrates."
    found = check_sections(paper({"introduction": INTRO, "methods": "Reactions were run in THF at 80 °C for 2 h overnight.", "results": results},
                                 full_text="\n\n".join([ABSTRACT, INTRO, results])))
    assert item(found, "results", "spread").status == "missing"


# ------------------------------------------------------------------ discussion and claims

def test_a_limitation_is_found_in_the_results() -> None:
    check = item(check_sections(paper()), "discussion", "limitations")
    assert check.status == "met" and "not as advantageous" in check.quote


def test_overcoming_a_limitation_is_not_admitting_one() -> None:
    results = RESULTS.replace(" Conditioning is not as advantageous for the constrained benchmark.", "")
    conclusion = "We show techniques for overcoming dataset limitations that improve VAEs."
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results, "discussion": conclusion}))
    assert item(found, "discussion", "limitations").status == "missing"


def test_a_strong_claim_about_this_work_is_flagged_but_not_one_about_earlier_work() -> None:
    results = RESULTS + " Deep learning revolutionized drug discovery. Our method is unprecedented in accuracy."
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    labels = [c.label for c in found["results"] if c.key == "overclaim"]
    assert labels == ["Strong claim: “unprecedented”"]


def test_prove_in_a_mathematical_paper_is_not_an_overclaim() -> None:
    results = RESULTS + " We prove that the bound holds. Theorem 1 states the bound."
    sections = {"introduction": INTRO, "methods": METHODS, "results": results}
    found = check_sections(paper(sections))
    assert not [c for c in found["results"] if c.key == "overclaim"]


# ------------------------------------------------------------------ article types and stability

def test_an_editorial_gets_no_checklist() -> None:
    found = check_sections(paper(article_type=pp.EDITORIAL))
    assert all(items == [] for items in found.values())


def test_a_review_is_not_asked_for_methods_or_data() -> None:
    sections = {"introduction": INTRO, "Ring-opening routes": RESULTS, "discussion": CONCLUSION}
    roles = {"introduction": "introduction", "Ring-opening routes": "thematic", "discussion": "discussion"}
    found = check_sections(paper(sections, roles, article_type=pp.MINI_REVIEW))
    keys = {c.key for items in found.values() for c in items}
    assert not keys & {"software_version", "seed", "replicates", "data_availability", "limitations", "spread"}


def test_the_same_paper_always_gets_the_same_checklist() -> None:
    first = check_sections(paper())
    assert all(check_sections(paper()) == first for _ in range(3))


# ------------------------------------------------------------------ a real preprint

CVAE = Path(__file__).resolve().parents[1] / "eval" / "papers" / "arxiv-2022-cvae-preprint.pdf"


@pytest.mark.skipif(not CVAE.exists(), reason="eval paper not on disk (eval/papers is git-ignored)")
def test_the_cvae_preprint() -> None:
    from services.parser import parse_document

    parsed = parse_document(CVAE.read_bytes(), CVAE.name)
    assert parsed.section_titles == {
        "introduction": "Introduction", "methods": "Methodology", "results": "Results", "discussion": "Conclusion",
    }
    found = check_sections(PaperText(parsed.full_text, parsed.abstract, parsed.sections, parsed.section_roles,
                                     pp.RESEARCH_ARTICLE, parsed.section_titles))
    wrong = item(found, "results", "figure_number")
    assert wrong is not None and "Fig. 3" in wrong.detail and "shown in Fig. 4 (a)" in wrong.quote
    assert "Keras, TensorFlow" in item(found, "methods", "software_version").detail
    assert item(found, "methods", "seed").status == "missing"
    assert item(found, "discussion", "limitations").status == "met"
    assert not [c for c in found["results"] if c.key == "abstract_number"]  # Table 2 holds 104.29 and 0.948


def test_an_overclaim_gets_a_fix_that_names_its_own_word() -> None:
    results = RESULTS + " Our method is unprecedented in accuracy and we prove that it generalises."
    found = check_sections(paper({"introduction": INTRO, "methods": METHODS, "results": results}))
    fixes = {c.label: c.fix for c in found["results"] if c.key == "overclaim"}
    assert "“unprecedented”" in fixes["Strong claim: “unprecedented”"] and "numbers" in fixes["Strong claim: “unprecedented”"]
    assert "show" in fixes["Strong claim: “we prove”"]
